import { ACTION_TYPE } from '../actions';

// Нам потребуется держать дополнительный флаг в стейте, для него нам потребуется новый редюсер. Здесь будут храниться данные о приложении в целом, таки как - надо ли сбросить форму.
const initialAppState = {
	// вводим флаг, который сигнализирует случился или не случился logout, то есть разлогинился ли пользователь
	wasLogout: false,
	// для модального окна
	modal: {
		// состояние модального окна, октрыто или закрыто
		isOpen: false,
		text: '',
		// ниже обработчики, в них будут функции. Мы будем хранить функции в стейте, но в идеале в стейте должны хранится примитивы, даже не примитивы, а информация, которая может JSONом преобразовываться в строку, а функция к таким не относится. Но здесь мы будем это делать, то есть хранить функции в стейте, потому что в таком случае можно будет обмениваться стейтом с сервером, когда это требуется, какие-то запросы делать и смотреть что у нас на сервере, а что на клиенте, но в нашем случае конкретно это не требуется. Вывод - в стейте конечно функций не должно быть6 но когда надо, то можно
		onConfirm: () => {},
		onCancel: () => {},
		// теперь при создании модального окна мы должны создать селекты, которые будут селектать текс и обработчики
	},
};

export const appReducer = (state = initialAppState, action) => {
	switch (action.type) {
		// здесь нам потребуется реагировать на экшен logout. Дело в том, что наши экшены диспатсятся по всем редюсерам
		case ACTION_TYPE.LOGOUT:
			// вернем новый стейт, в котором изменится одно поле wasLogout, то есть был логаут. Здесь мы возвращаем логаут измененным. Инвертируем стейт возлогаут итогда у нас при каждом нажатии на logout будет меняться флаг wasLogout с false на true и наоборрот и так до бесконечности. Что нам это даст? Теперь переходим в файл authorization.jsx к компоненту useEffects
			return {
				...state,
				wasLogout: !state.wasLogout,
			};
		// Создадим обработку дейтсвий модального окна
		case ACTION_TYPE.OPEN_MODAL:
			return {
				// развернем старый стейт
				...state,
				// теперь разворачиваем стейт конкретно модального окна, так как весь стейт у нас не только для модального окна, но в нем еще вложенный modal есть, поэтому соблюдаем вложенность, обновляем только свойство modal
				modal: {
					...state.modal,
					// принимаем payload (нагрузочные данные), который будут в action, то есть отгрузим сюда эти данные
					...action.payload,
					isOpen: true,
				},
			};
		case ACTION_TYPE.CLOSE_MODAL:
			// сбросим данные, чтобы не оставались данные от предыдущего открытия. Здесь нам не нужно разворачивать старый стейт, мы просто разворачиваем начальный стейт initialAppState, потому что мы уверены в корректности начального стейта initialAppState
			return initialAppState;

		default:
			return state;
	}
};
