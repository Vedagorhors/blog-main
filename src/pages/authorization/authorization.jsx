import { useState } from 'react';
import { useDispatch, useSelector } from 'react-redux';
import { Link, Navigate } from 'react-router-dom';
import { useForm } from 'react-hook-form';
import * as yup from 'yup';
import { yupResolver } from '@hookform/resolvers/yup';
import { server } from '../../bff';
import { AuthFormError, Button, H2, Input } from '../../components';
import { useResetForm } from '../../hooks';
import { setUser } from '../../actions';
import { selectUserRole } from '../../selectors';
import { ROLE } from '../../constants';
import styled from 'styled-components';

// зададим схему для формы.  С помощью схемы можно задавать вид полей и их валидацию
const authFormSchema = yup.object().shape({
	login: yup
		.string()
		.required('Заполните логин')
		.matches(/^\w+$/, 'Неверно заполнен логин. Допускаются только буквы и цифры')
		.min(3, 'Неверно заполнен пароль. Минимум 3 символа')
		.max(15, 'Неверно заполнен пароль. Максимум 15 символов'),
	password: yup
		.string()
		.required('Заполните пароль')
		.matches(
			/^[\w#%]+$/,
			'Неверно заполнен пароль. Допускаются буквы, цифры и знаки # %',
		)
		.min(6, 'Неверно заполнен пароль. Минимум 6 символов')
		.max(30, 'Неверно заполнен пароль. Максимум 30 символов'),
});

const StyledLink = styled(Link)`
	text-align: center;
	text-decoration: underline;
	margin: 20px 0;
	font-size: 18px;
`;

// Здесь была константа ErrorMessage. Её при рефакторинге кода перенесли в отдельный файл auth-form-error.js и вместо ErrorMessage назвали компонент AuthFormError

const AuthorizationContainer = ({ className }) => {
	const {
		register,
		// добавляем функцию reset, её нужно вызвать, чтобы форма сбросилась, а reset вызывается, когда нажимается кнопка logout
		reset,
		handleSubmit,
		formState: { errors },
	} = useForm({
		defaultValues: {
			login: '',
			password: '',
		},
		resolver: yupResolver(authFormSchema),
	});

	// Чтобы вывести ошибку error используем локальный стейт. formError -ошибка формы
	const [serverError, setServerError] = useState(null);

	const dispatch = useDispatch();

	// Авторизация  - это у нас компонент с контентом (файл authorization.jsx), а кнопка logout у нас вообще в шапке. То есть по нажатию кнопки в шапке мы должны каким-то образом сообщить в компонент авторизации (файл authorization.jsx), что нужно сделать сброс reset. Есть такой способ – для этого используется функционал redux, которого мы не рассматривали в уроках. Нам потребуется хук useStore, а также метод  unsubscribe, который вернет нам метод  subscription, который есть в объекте store. Этот метод subscribe() будет вызываться каждый раз, когда у нас будут происходить изменения в стейте, но нам нужно реагировать не на любые изменения, а только на те, в которых меняется флаг wasLogout.
	// Теперь в компоненте авторизации authorization.jsx мы можем следить за стейтом и когда у нас измениться флаг wasLogout мы запустим функцию reset, таким образом сбросим нашу форму. Сделать это лучше всего в хуке useEffect. Нам потребуется создать подписку и отписку. Всё это делается при монтировании компонента

	// store перенесли во вновь созданный файл use-reset-form куда также перенесли useEffect
	// const store = useStore();

	// Сделаем редирект на главную страницу с помощью условного рендеринга и роутера
	// используем селектор для того, чтобы получить роль
	const roleId = useSelector(selectUserRole);

	// Здесь был useEffect, но так как он у нас повторяется в двух компонентах, в Authorization и здесь в Registration, то делаем рефакторинг кода. useEffect можно вынести в отдельный компонент. Нужно там создать кастомный хук, который будет заниматься сбросом формы.
	// Теперь здесь вместо useEffect вызываем созданный с useEffect компонент кастомный хук useResetForm и в него передаем функцию reset, так как там в файле use-reset-form.js компонент useResetForm принимает reset
	useResetForm(reset);

	const onSubmit = ({ login, password }) => {
		// когда мы нажимаем кнопку Войти, мы отправляем логин и пароль на сервер, для того, чтобы он нам вернул сессию. На сервер мы отправляем с помощью нашего BFF-эмулятора, у которог есть описанная функция authorize для авторизации.
		// В реальном проекте мы были делали fetch запрос с адресом и по этому адресу мы бы обращались на прокси, то есть на BFF (у меня это файл server.js), но так как у нас эмулятор, то мы делаем проще - импортируем как бы сервер и к нему обращаемся через JS.
		// Итак обращаемся на наш эмулятор на сервер, в котором вызываем функцию authorize и передаем ей логин и пароль, которые уже прошли валидацию через yup, то есть они уже корректные. После того, как придет ответ с сервера, мы должны его обработать через then. Из объекта сразу извлекаем ошибку и ответ then(({error, res})
		// Обращаемся к функции authorize к серверу, то есть к нашему BFF и здесь в ответе res мы будем принимать ключ, который будет гарантировать нам то, что мы авторизовались, с помощью которого мы сможем проверять. Этот ключ мы будем отправлять с каждым запросом (запросы типа редактировать статью, удалить статью, удалить комментарий). Этот ключ на клиенте мы будем хранить так - записывать в redux store в state для user, то есть для текущего пользователя. поле назовем session Наш хэш будет символизировать нашу сессию этого пользователя. ДОбавим поле session в файл user-reducer.js
		// В ответе res (это response - ответ) мы получаем готовый хэш, проверяем ошибку и если ошибка есть, то мы прерываем работу кода, а если ошибки нет, то идем дальше по коду и передаем экшен с помощью dispatch
		server.authorize(login, password).then(({ error, res }) => {
			if (error) {
				// установим то, что получили с сервера, текст этой ошибки
				setServerError(`Ошибка запроса: ${error}`);
				return;
			}
			// из экшенов (папка actions) импортировал один экшен setUser. Делаю его диспатч, устанавливаем всё, что получаем в ответ, это и есть данные пользователя, там и сессия в них лежит. Указываем туда ответ res от сервера. Таким образом я сохраняю данные о том, что авторизация прошла
			dispatch(setUser(res));
		});
	};

	// получим сообщение об ошибке, которое мы уже выведем в разметку, оно будет составляться из нескольких ошибок. Разделим ошибки на две части - ошибка формы formError и ошибка сервера serverError. Если ошибки при валидации и ошибки,которые приходят с сервера
	const formError = errors?.login?.message || errors?.password?.message;
	const errorMessage = formError || serverError;

	// Сделаем редирект на главную страницу с помощью условного рендеринга и роутера
	// используем селектор для того, чтобы получить роль
	// const roleId = useSelector(selectUserRole);
	// после получения роли, перед тем, как отрендерить нижеприведенную разметку мы проверяем роль. На главную страницу мы попадем когда залогиниваемся, то есть если мы не гость, то есть мы уже авторизовались, то переходим на главную страницу
	if (roleId !== ROLE.GUEST) {
		// если роль гость, то возвращаем разметку с компонентом Navigate  в котором указываем адрес главной страницы "/"
		return <Navigate to="/" />;
	}

	return (
		<div className={className}>
			{/* когда создаю отельный компонент, а не просто тэг, как вначале сделали, то потом нужно импортировать данный компонент в нужный файл (в данном случае в этот) и заменить в коде имя тэга на имя компонента (в данном случае h2 на H2) */}
			<H2>Авторизация</H2>
			<form onSubmit={handleSubmit(onSubmit)}>
				<Input
					type="text"
					placeholder="Логин..."
					// это добавил я: autoComplete="username"
					autoComplete="username"
					{...register('login', {
						// сделаем сброс серверной ошибки. То есть когда мы заполняем поле логина, то появляется сообщеие предупреждение об ошибке, но потом мы продожаем писать логин и ошибка должна сама исчезать, но она не пропадает, поэтому сделаем так, чтобы она пропадала при условиях когда логин удовлетворяет требованиям. Добавим свой onChange для функции register
						onChange: () => setServerError(null),
					})}
				/>
				<Input
					type="password"
					placeholder="Пароль..."
					// это добавил я: autoComplete="current-password"
					autoComplete="current-password"
					{...register('password', {
						// сделаем сброс серверной ошибки. Также как для логина
						onChange: () => setServerError(null),
					})}
				/>
				{/* Если будет ошибка формы, то мы блокируем кнопку */}
				<Button type="submit" disabled={!!formError}>
					Авторизоваться
				</Button>
				{errorMessage && <AuthFormError>{errorMessage}</AuthFormError>}
				<StyledLink to="/register">Регистрация</StyledLink>
			</form>
		</div>
	);
};

// задаем стилизацию компонента AuthorizationContainer
// // Делаем поля авторизации в столбик. Можно для этого создать стилизованный компонент Form и задать для него стили, но мы сделаем другим способом, применим особый синтаксис & > form {}, который позволяет обрабатывать для стилизованного компонента не только его самого, но и еще какие-то вложенные теги, обращаясь к ним по именам тегов, классов, как в обычном css это работает: Для обработки вложенных тегов компонента применим такой подход, обращаясь к нему по именам тегов, классов:
export const Authorization = styled(AuthorizationContainer)`
	display: flex;
	flex-direction: column;
	align-items: center;

	& > form {
		display: flex;
		flex-direction: column;
		width: 260px;
	}
`;
