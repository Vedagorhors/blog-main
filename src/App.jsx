import styled from 'styled-components'; // вместо CSS-модулей здесь будем использовать Styled-components, просто для примера, потому что ранее в уроках мы использовали только css-модули

// Создаем стилизованный компонент Div просто для проверки. То есть обращаемся к объекту styled, который мы импортировали, потом через точку пишет тэг какой мы хотим использовать, который будет в основе стилизованного компонента. То есть получается был тэг, а стал компонент Div со стилями
// Вызываем функцию с помощью строкового шаблона (бэктики `` обозначают строковый шаблон) и когда мы бэктики пишем вплотную к переменной (div) это означает, что мы вызываем эту функцию. Вот div это у нас функция, которая находится в объекте styled. Так вот мы вызываем эту функцию и передаем в неё определённые аргументы, которые содержат текст из строкового шаблона и переменные, если мы их используем. Эта функция выполняется и что-то нам возвращает, в данном случае возвращает стилизованный компонент Div.
const Div = styled.div`
	text-align: center;
`;
export const App = () => {
	return (
		<Div>
			<i className="fa fa-calendar"></i>
			<div>Привет, Ведагор!</div>
		</Div>
	);
};
