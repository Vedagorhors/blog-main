import { useCallback } from 'react';
import { useSelector } from 'react-redux';
import { selectUserSession } from '../selectors';
import { server } from '../bff';

// Хук useServer запрашивает сессию из redux-store с помощью хука useSelector и тогда она здесь в замыкании лежит. При этом useServer нам возвращает функцию, в которую мы уже можем отправлять параметры запроса operation, ...params, то есть это имя операции и параметры для неё.
export const useServerRequest = () => {
	const session = useSelector(selectUserSession);

	// Формируем данные для запроса и эти данные уже будут включать сессию либо нет, а как мы узнаем - нужно посмотреть что за операция пришла. Если операция включена в 'register', 'authorize', то мой реквест будет определенного вида, а если не включена, то другого
	// Вот две операции register и authorize, для которых у нас исключения срабатывают, то есть если эти операции register и authorize, то нам сессия не требуется и поэтому мы её не отправляем. Но для всех любых других операций ссесию мы будем слать и на сервере она будет проверяться.

	// вернем функцию. Пока авторизация пользователя та же самая, у нас и ссылка на нашу функцию будет одинаковая. Ну то есть если сессия одинаков и пользователь один и тот же, то и функция для запроса сервера будет та же самая, ссылка та же самая даже будет. Это значит, что переменная requestServer (в файле users.jsx) будет всегда с одной и той же ссылкой для одного и того же пользователя и наш useEffect (в файле users.jsx) не будет заново вызываться, пока не измениться эта ссылка, то есть пока не смениться пользователь. То, что нам и нужно. Если пользователь сменится, то нам нужно уже заново то всё вызвать, что указано в файле users.jsx и посмотреть, есть ли ошибка доступа
	return useCallback(
		(operation, ...params) => {
			// здесь выбираем какие должны быть параметры при отправке на сервер
			const request = ['register', 'authorize', 'fetchPost'].includes(operation)
				? params
				: [session, ...params];
			// и отправляем когда эта функция вызывается
			return server[operation](...request);
		},
		[session],
	);
};
// здесь нам не нужна сессия, это открытая информация и каждый может читать статьюы
