// создадим трансформера для преобразования формата пользователя из базы данных в формат обычного пользователя. Трансформеры - это функции, которые преобразовывают данные, то есть берут формат из базы данных и преобразовывают его в другой, который нам болььше подходит.
// Получается преобразование одного объекта в другой объект
// dbUser - юзер из базы данных. Выводить будем обычного юзера
export const transformUser = (dbUser) => ({
	// делаем маппинг
	id: dbUser.id,
	login: dbUser.login,
	password: dbUser.password,
	registeredAt: dbUser.registed_at,
	roleId: dbUser.role_id,
});
