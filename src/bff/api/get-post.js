// Создадим функцию getPost по аналогии с getUser. А чтобы не запрашивать список всех пользователей getUsers, мы запросим конкретный логин с помощью ?login=${loginToFind} - то есть дописали запрос и подставили то, что мы ищем. Вместо одиночных кавычек поставили бэктики ``, так как используем шаблонную строку ${}
// здесь нужно указывать async, await, потому что мы указываем несколько операций
// Мы возвращаем поиск из базы данных и фильтруем по логину. Нам вернется не одиин объект, а массив из объектов, в которых совпадает логин с указанным логином. Поэтому мы возвращаем данные loadedUsers.json() и вернем нулевой элемент [0]. А .? - это для подстраховки, хотя мы точно вернем массив, тогда убираем .?
import { transformPost } from '../transformers';

export const getPost = async (postId) =>
	// обращаемся просто по id (postId)
	fetch(`http://localhost:3005/posts/${postId}`)
		.then((loadedPost) => loadedPost.json())
		// json возвращает promise, поэтому делаем через then. Здесь мы loadedUser извлечем из массива деструктуризации и вернем его же loadedUser
		.then(
			// вызываем функцию transformUser и передаем туда загруженную статью. Так как здесь не поиск, то здесь ммасива не будет, как было в get-user,  так как мы сразу получаем данные
			(loadedPost) => loadedPost && transformPost(loadedPost),
		);

// теперь создадим трансформер, файл transform-post.js
