import { getUser } from '../api';
import { sessions } from '../sessions';

export const authorize = async (authLogin, authPassword) => {
	// получаем только одного пользователя
	const user = await getUser(authLogin);

	if (!user) {
		return {
			error: 'Такой пользователь не найден',
			res: null,
		};
	}

	// мы убедились, что пользователь есть, мы его получили и теперь проводим деструктуризацию и извлекаем из user поля id, login, password, дата регистрации registeredAt, roleId
	const { id, login, password, roleId } = user;

	// Если пользователь найден, то сработает ниже приведенный код, следующая проверка

	// Если пароль пользователя для авторизации не равен паролю в наденном пользователе, то возвращаем ошибку. Так как мы провели диструктуризацию и извлекли из user поля, то теперь можно ниже писать, например, не user.password, а просто password  и т.п.
	if (authPassword !== password) {
		return {
			error: 'Не верный пароль',
			res: null,
		};
	}

	// Если пользователь найден и пароль совпал, то мы возвращаем пользователю сэссию, с помощью которой он сможет выполнять дополнительные действия, так как он получит больше прав после прохождения авторизации. То есть когда мы авторизовались, то пусть сервер пришлет нам не только сессию, но и все данные о пользователе в ответе res
	// после деструктуризации user можно упростить запись, например вместо id: user.id писать просто id: id, но когда у ключа и его значения совпадает имя, то пишем еще проще просто id
	const sessionHash = await sessions.create(user);

	// console.log('Авторизация успешна, хэш сессии:', sessionHash);

	return {
		error: null,
		res: {
			id,
			login,
			roleId,
			// дата регистрации registeredAt при запросе одного пользователя не нужна, так как эту информацию мы выводим только в списке пользователей, а не для одного. На клиента нужно отправлять, только то, что требуется, лишнюю информацию не нужно отправлять это и не безопасно и не. соответствует лучшим практикам, это не корректный подход
			// создание сессии это создание хэша. Мы с базы данных передаем в наш сервер BFF все данные юзера и пусть BFF их хранит
			session: sessionHash,
		},
	};
};
