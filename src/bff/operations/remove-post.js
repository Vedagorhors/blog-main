// Операция по удалению комментария. Напишем её на основе кода из подобного файла по удалению

import { deleteComment, deletePost, getComments } from '../api';
import { sessions } from '../sessions';
import { ROLE } from '../constants';

// removePostComment - функция удаления комментария из статьи
export const removePost = async (hash, id) => {
	// для этого метода fetchUsers должен быть свой список ролей, которые могут запросить роли. Получается для каждого метода будем задавать это массив  с ролями доступа accessRoles и таким образом будем проверять доступ. Здесь удалять статью может только администратор
	const accessRoles = [ROLE.ADMIN];

	// Проверяем доступ в сессиях, что у пользователя есть права на получение списка ролей. Это может делать только администратор. Если проверка не пройдена, то отправляем ошибку. (! - проверка провалилась)
	// Эту сессию userSession мы отправляем для проверки доступа, а также отправляем в нашу утилиту accessRoles (роли с доступом), то есть мы отправляем массив с теми ролями, для которых эта операция доступна, а это определяет сама операция, она знает для кого она доступна на сервере
	// Если доступа нет, то мы об этом сообщаем: error: 'Доступ запрещен'
	const access = await sessions.access(hash, accessRoles);
	// console.log('Результат проверки доступа:', access);

	if (!access) {
		return {
			error: 'Доступ запрещен',
			res: null,
		};
	}

	// Удаляе статью по id
	await deletePost(id);

	// Теперь удаляем все коммментарии у удаленной статьи
	// получааем все комментарии по postId, здесь это у нас id. Затем проходимся по полученным комментариям в массиве и удаляем каждый
	const comments = await getComments(id);
	// Мапим, принимаем комментарий, достаем из него id, переименуем id в commentId, чтобы не путаться с id поста PostId и возвращаем обращение для удаления комментария deleteComment(commentId) по этому commentId. Получается на выходе у нас будет массив промисов и мы можем завернуть их в Promise.All. В JSON сервере к сожалению нет возможности удалять пачку каких-то строчек, значений, а только по одной. Вот у нас Promise.all и мы ждем когда он полностью отработает.

	Promise.all(comments.map(({ id: commentId }) => deleteComment(commentId)));

	await deleteComment(id);

	// Теперь нам нужно в файле post.jsx удалить данные из redux store

	// здесь просто отвечаем, что всё хорошо
	return {
		error: null,
		res: true,
	};
};

// Теперь нужно создать запрос (обращение) в базу данных для осуществления удаления статьи, это будет deletePost. Создадим в папке api файл delete-post.js
