// Создадим операцию сохранения статьи, то есть чтобы обработать данные на сервере создадим для этого операцию. Здесь будет обновление.

import { addPost, updatePost } from '../api';
import { ROLE } from '../constants';
import { sessions } from '../sessions';
import { transformPost } from '../transformers';

// у нас только две операции работают без сессии - это авторизация и регистрация
export const savePost = async (hash, newPostData) => {
	// для того, чтобы иметь права редактировать статью, пользователь должен быть администратором
	const accessRoles = [ROLE.ADMIN];

	// Проверяем доступ в сессиях, что у пользователя есть права на получение списка ролей. Это может делать только администратор. Если проверка не пройдена, то отправляем ошибку. (! - проверка провалилась)
	// Эту сессию userSession мы отправляем для проверки доступа, а также отправляем в нашу утилиту accessRoles (роли с доступом), то есть мы отправляем массив с теми ролями, для которых эта операция доступна, а это определяет сама операция, она знает для кого она доступна на сервере
	// Если доступа нет, то мы об этом сообщаем: error: 'Доступ запрещен'
	const access = await sessions.access(hash, accessRoles);
	if (!access) {
		return {
			error: 'Доступ запрещен',
			res: null,
		};
	}

	// Пользователь с каждым запросом на сервер, будет присылать нам хэш, который сервер ему выдал в процессе авторизации. А хэш мы будем хранить в поле session в redux store в файле user-reducer session: null. Если null, значит юзер не авторизованный

	// Если доступ есть, то совершаем операцию сохранения статьи в случае, если id равен пустой строке, то мы создаем статью, а если же id не равен пустой строке, то мы значит обновляем статью
	// const updatedPost = await updatePost(newPostData);
	const savedPost =
		newPostData.id === ''
			? await addPost(newPostData.imageUrl, newPostData.title, newPostData.content)
			: await updatePost(
					newPostData.id,
					newPostData.imageUrl,
					newPostData.title,
					newPostData.content,
				);
	// добавим обработку создания статьи, для этого в папке api создадим файл add-post.js (хотя лучше наверное назвать файл create-post.js), но раз опдобные файлы у нас там с названием add, то оставим add-post

	// возвращаем, что ошибок нет и роль установилась, то есть res (response) равно true, возвращаем данные о созданной статье
	return {
		error: null,
		res: transformPost(savedPost),
	};
};

// единственное что доступно пользователю, который обращается к серверу на BFF, это список операций.
// Список доступен через объект сервера. Пользователю должны быть недоступны какие-то возможности, которые напрямую обращаются в базу данных, это не безопасно.

