import { getUsers } from '../api';
import { sessions } from '../sessions';
import { ROLE } from '../constants';

// мы должны проверить имеет ли пользователь права, для того, чтобы получить роли. userSession - сессия пользователя.
// Нужно отметить, что для авторизации, регистрации, логаута подобная проверка доступа не нужна проверка, эти функции доступны любому пользователю
export const fetchUsers = async (hash) => {
	// для этого метода fetchUsers должен быть свой список ролей, которые могут запросить роли. Получается для каждого метода будем задавать это массив  с ролями доступа accessRoles и таким образом будем проверять доступ
	const accessRoles = [ROLE.ADMIN];

	// Проверяем доступ в сессиях, что у пользователя есть права на получение списка ролей. Это может делать только администратор. Если проверка не пройдена, то отправляем ошибку. (! - проверка провалилась)
	// Эту сессию userSession мы отправляем для проверки доступа, а также отправляем в нашу утилиту accessRoles (роли с доступом), то есть мы отправляем массив с теми ролями, для которых эта операция доступна, а это определяет сама операция, она знает для кого она доступна на сервере
	// Если доступа нет, то мы об этом сообщаем: error: 'Доступ запрещен'
	const access = await sessions.access(hash, accessRoles);
	// console.log(access);

	if (!access) {
		return {
			error: 'Доступ запрещен',
			res: null,
		};
	}

	// Пользователь с каждым запросом на сервер, буде присылать нам хэш, который сервер ему выдал в процессе авторизации. А хэш мы будем хранить в поле session в redux store в файле user-reducer session: null. Если null, значит юзер не авторизованный

	// Если пользователь имеет права, то делаем запрос getUsers к базе данных. И получим список ролей и их же отправим. В отдельном файле get-roles.js создадим запрос к базе данных getRoles
	// дали роль юзеру, если у него есть доступ
	const users = await getUsers();
	// console.log(user);

	// и уже из нового юзера мы возьмем данные. Создаем сразу сессию, авторизуем
	return {
		error: null,
		res: users,
	};
};

// Теперь можем использовать эту операцию fetchRoles на фронтенде в компоненте user-row
