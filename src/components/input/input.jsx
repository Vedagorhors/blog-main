// нужно передать ref. Это не обычный проп, его нужно передавать с помощью спец. функции forwardRef и потом в эту функцию завернуть нужный компонент
import { forwardRef } from 'react';
import styled from 'styled-components';

// Чтобы задать ширину инпуту но инпут используется в разных местах и не везде эта ширина нужна, поэтому, чтобы ширина применилась на конкретном инпуте, что мы стилизуем ниже компонент Input (не <input... />), мы передадим ширину width отдельно от всех пропсов ...props, то есть извлечем из пропсов, а потом именно width применим к конкретному компоненту Input следующим образом: width: ${({ width = 'auto' }) => width}; То есть, чтобы нам достать что-то из пропсов мы используем переменную строкового шаблона &{} ынутри которой у нас будет находиться функция.  То есть здесь мы уже принимаем этот пропс width, а еще по умолчанию задаем ему значение 100%, на случай, если никакого значения для пропса width мы не примем с пропса. Ширина 100% по умолчанию даст нам возможность задавать ширину только контейнера, например для тэга form, а весь контент, то есть input, button, - они будут подстраиваться под ширину этого контейнера. Для тэга form в файле authorization.jsx задаем ширину width: 260px; , ну а все что внутри тэга (input, button) должно растянуться по ширине под размер 260px.
// И получается, что мы не транслируем wight в <input... />, где wight не нужна
// Здесь оборачиваем компонент в forwardRef и дописываем ref отдельным аргументом после пропсов, а в return мы ref передаем как обычный проп
const InputContainer = forwardRef(({ className, width, ...props }, ref) => {
	return <input className={className} {...props} ref={ref} />;
});

export const Input = styled(InputContainer)`
	width: ${({ width = '100%' }) => width};
	height: 40px;
	margin: 0 0 10px;
	padding: 10px;
	font-size: 18px;
	border: 1px solid #000;
`;
