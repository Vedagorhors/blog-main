// Подключаем Express, чтобы создать общий роутер для всех API-эндпоинтов.
const express = require("express");

// Router объединяет обработчики запросов, но сам не запускает HTTP-сервер.
// mergeParams: true позволяет вложенному роутеру видеть параметры родительского
// маршрута, например :postId. В текущем месте подключения параметров нет,
// поэтому эта настройка пока не влияет на работу; оставляем её как в материале курса.
const router = express.Router({ mergeParams: true });

// Подключаем три группы маршрутов. Express добавляет указанный здесь путь
// к пути обработчика внутри соответствующего файла.
// В app.js этот общий роутер подключён через app.use("/api", routes),
// поэтому итоговый URL складывается из /api + путь группы + путь обработчика.

// В auth.js уже указаны /register, /login и /logout, поэтому здесь достаточно /.
// Например: POST /api + / + /login → POST /api/login.
// Слеши здесь обозначают границы подключения, а не складываются в двойной слеш.
router.use("/", require("./auth"));

// В post.js пути начинаются с / или /:id, без повторного префикса /posts.
// Например: GET /api/posts получает список статей,
// GET /api/posts/:id — одну статью,
// POST /api/posts/:id/comments — добавляет комментарий.
router.use("/posts", require("./post"));

// Аналогично подключаем работу с пользователями:
// GET /api/users — список, GET /api/users/roles — роли,
// PATCH /api/users/:id — изменение роли пользователя.
// Проверки authenticated и hasRole находятся в файлах групп маршрутов.
// Здесь не ставим общую проверку входа: регистрация, вход и просмотр статей
// должны оставаться доступными гостям.
router.use("/users", require("./user"));

// Экспортируем собранный роутер. В app.js require("./routes") автоматически
// загружает этот index.js, после чего app.use("/api", routes) подключает его к серверу.
module.exports = router;
