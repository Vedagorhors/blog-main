// миддлевара hasRole для проверки ролей пользователя. Она надеется, что в объекте запроса req уже есть пользователь req.user = user, то есть до неё нужно будет обязательно подключить authenticated.

module.exports = function (roles) {
  return (req, res, next) => {
    // hasRole будет отдавать функцию, которая вернет функцию. Зачем это нужно? Мы будем принимать массив ролей и возвращать функцию, которая будет проверять, что у пользователя есть одна из этих ролей.
    if (!roles.includes(req.user.role)) {
      // Если у него этой роли нет, тогда мы отправляем на фронтенд ошибку
      res.send({ error: "Access denied" });

      return;
    }
    // иначе пропускаем пользователя дальше
    next();
  };
};
