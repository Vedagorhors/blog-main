// контроллер для комментариев

// здесь нам понадобится добавление, удаление и получение списка для поста

// подключаем модель
const Comment = require("../models/Comment");
const Post = require("../models/Post");

// add. Контроллер добавления комментариев. Он принимает идентификатор поста postId и содержимое комментария comment
async function addComment(postId, comment) {
  // создаем новый документ комментария.
  const newComment = await Comment.create(comment);
  // У постов в модели есть массив комментариев. Нам нужно найти наш пост и добавить в него комментарий. Для этого используем метод findByIdAndUpdate. Передаем туда postId и нужно сказать как-то, чтобы комментарий добавился в массив - это можно сделать операцией $push. Мы говорим в какой массив добавить и что добавить - можем передать туда инжентификатор, а можем передать полную модель, разницы не будет. Теперь мы помимо создания документа ещё привязываем его к посту
  await Post.findByIdAndUpdate(postId, { $push: { comments: newComment } });
  // После проверки в Thunder Client по добавлению комментария (см. app.js), видим в ответе по запросу добавления комментария какие-то появлись вспомогательные поля, а у автора просто передает идентификатор. Если посмотрим на сам пост, то в комментарии у него тоже идентификатор. Оперировать этим будет неудобно с фронтенда, поэтому добавим полезную логику, а именно в комментариях нам нужно рпевратить автора из безликого идентификатора в объект с информацией об авторе. Так как в комментах у нас есть связь с автором (в Comments.js в CommentSchema), то мы можем попросить mongoose заполнить информацию об авторе за нас. Говорим, какое поле нам нужно превратить из идентификатора в объект, который содержит информацию по этому идентификатору. В таком виде при добавлении коммента (смотрим в Thunder Client) в авторе будет лежать информация о пользователе. Сделаем тоже самое и для постов.
  await newComment.populate("author");

  return newComment;
}

// delete

async function deleteComment(postId, commentId) {
  // сначала удалим сам комментарий
  await Comment.deleteOne({ _id: commentId });
  // теперь уберем у поста этот комментарий. Используем операцию не push, а pull - она позволяет убрать элемент из массива ипередаем туда идентификатор commentId. Помним о том, что мы можем работать как с документами, так и с идентификаторами.
  await Post.findByIdAndUpdate(postId, { $pull: { comments: commentId } });
}

