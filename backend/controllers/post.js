// Подключаем модель
const Post = require("../models/Post");

// Контроллер для постов и комментариев

// add
// добавляем контроллер.
// Добавим разворачивание комментариев еще в редактирование и добавление поста, потому что это операции, которые будут отправлять нас на страницу одного поста, а там информация о комментариях сразу будет очень полезна. Проверим, что это работает в Thunder Client
async function addPost(post) {
  // создадим populate
  const newPost = await Post.create(post);

  await newPost.populate({
    path: "comments",
    populate: "author",
  });

  return newPost;
}

// edit
async function editPost(id, post) {
  const newPost = await Post.findByIdAndUpdate(id, post, {
    returnDocument: "after",
  });

  await newPost.populate({
    path: "comments",
    populate: "author",
  });

  return newPost;
}

// delete
function deletePost(id) {
  return Post.deleteOne({ _id: id });
}

// get list with search and pagination - получение списка постов. Создадим функцию. Она принимает три аргумента - это поиск, по умолчанию это пустая строка, limit - сколько элементов находится на странице, по умолчанию поставим 10 и третий аргумент page - текущая страница, на которой находится пользователь, по умолчанию будет 1.
// Теперь нам необходимо найти все посты по этому поиску search, потом пропустить столько-то постов, потому что мы можем находится не на первой странице, а дальше получить количество постов равное лимиту. При этом нам нужно сказать фронтенду, а сколько вообще таких страниц, потому что нужно отображать паджинацию. Без переключения по страницам будет очень не удобно пользоваться лентой постов, поэтому мы делаем сразу два запроса и, чтобы онги шли параллельно, будем использовать Promise.all.
async function getPosts(search = "", limit = 10, page = 1) {
  // диструктуризуем эи данные
  const [posts, count] = await Promise.all([
    // Первый запрос будет на поиск постов. Нам необходимо искать по search - чтобы это делать и искать по какому-то кусочку текста, а не пополному совпадению, мы используем регулярные выражения. Ищем title и передаем объект, где будет поле $regex  и в него мы передадим нашу подстроку, которую будем искать и поле $options, туда мы передаем i - это значит, что наш поиск будет регистронезависимым, то есть не важно пользователь вводил большие или маленькие буквы, мы все равно найдем для него пост.
    Post.find({ title: { $regex: search, $options: "i" } })
      // испльзуем .limit для того, чтобы отрезать нужное количество постов.
      .limit(limit)
      // дальше нам необходимо пропустить все предыдущие страницы - делаем это с помощью метода skip и туда передаем сколько постов нам нужно пропустить и это количество нужно рассчитать. Расчитывается так - количество страниц минус 1 умноженное на лимит. То есть, если мы будем находиться на третьей странице, то 3 -1 * 10 = 20. Получается мы пропускаем 20 постов и берем следующие 10.
      .skip((page - 1) * limit)
      // Отсортируем, чтобы мы получали новые посты сверху с помощью метода sort. В него мы передаем объект, который описывает а как нужно сортировать, по какому полю мы будем сортировать по createdAt  и каким образом. Мы будем сортировать по убыванию, то есть -1, если бы мы поставили 1, то это было бы по возрастанию, самые старые посты были бы в самом начале.
      .sort({}),
    // посты мы нашили и теперь нам нужно посчитать, а сколько же есть таких постов. Отфильтруем посты по $regex  и посчитаем, а сколько их вообще есть.
    Post.countDocuments({ title: { $regex: search, $options: "i" } }),
  ]);
  // вернем данные posts, а вместо count будем использовать lastPage. lastPage рассчитываем так - нам необходимо поделить count на количество станиц limit и округлить вверх Math.ceil
  return {
    posts,
    lastPage: Math.ceil(count / limit),
  };
}

// get item (получение одного поста). При получении одного поста будем разворачивать его комментарии. Так как populate работает только на один уровень в глубину, то при получении одного поста увидим информацию о комментариях, но автор снова будет идентификатором, то есть набор букв и цифр. Для постов populate разворачивает получается комментарии, а для того, чтобы развернуть авторов нам нужно вызвать вложенный populate  иделаем это так -  вместо строки мы пердадим объект, где говорим путь который нам нужно запопьюлейтить и дальше какое-то количество дополнительных команд - фильтрация, сортировка или вложенный populate. Теперь, если мы получим пост, то у него в комментариях будут объекты комментариев, а в авторе будет объект информации о том, кто оставил комментарий. Как мы видим эти контроллеры возвращают данные, в которых содержатся служебная информация икакие-то поля, которые нам нужно переименовать, поэтому пишем маппер для коммментариев, файл mapComment
function getPost(id) {
  return Post.findById(id).populate({
    path: "comments",
    populate: "author",
  });
}

