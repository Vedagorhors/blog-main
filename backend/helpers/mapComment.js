// Маппер для комментариев. Копируем полученные данные комментария (в Thunder Client) и здесь вставляем и редактируем на то, что мы хотим видеть - сохраняем контент, в качестве автора возвращаем только логин, идентификатор переименовываем, пишем comment._id, createdAt меняем на publishedAt, а updatedAt  и версию убираем.

module.exports = function (comment) {
  return {
    content: comment.content,
    author: comment.author.login,
    id: comment._id,
    publishedAt: comment.createdAt,
  };
};

// используем этот маппер в app.js. Добавим также этот маппер в маппер постов, так как в постах могут быть комментарии, но важный момент - в комментариях могут храниться идентификаторы либо развернутые комментарии в виде объектов. Нам нужно идентификаторы оставлять как есть, они нам пригодятся, например,  на списке постов, там нам достаточно знать количество комментариев либо мы будем превращать комментарии в правильные объекты с помощью маппера mapComment.
